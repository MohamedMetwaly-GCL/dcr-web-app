def t_status(val: str, lang: str = DEFAULT_LANG) -> str:
    """Translate a canonical status string for display only; returns original if unknown or EN."""
    if not val:
        return val or ""
    norm = normalize_lang(lang)
    if norm == "en":
        return str(val)
    raw = str(val).strip()
    collapsed = " ".join(raw.lower().split())
    normalized_comma = re.sub(r"\s*,\s*", ",", collapsed)
    key = _STATUS_KEY_MAP.get(collapsed) or _STATUS_KEY_MAP.get(normalized_comma)
    if key:
        return t(key, norm)
    return raw


def t_dt(code: str, default_name: str = "", lang: str = DEFAULT_LANG) -> str:
    """Translate a canonical document type code for display only while preserving abbreviations."""
    norm = normalize_lang(lang)
    c = str(code or "").strip().upper()
    fallback = str(default_name or code or "").strip()
    if norm == "en" or not c:
        return fallback
    key = f"dt_name.{c}"
    translated = t(key, norm)
    if translated and translated != key and not translated.startswith("dt_name."):
        return translated
    return fallback


def t_col(col_key: str, default_label: str = "", lang: str = DEFAULT_LANG) -> str:
    """Translate a built-in system column key for display only; fall back to default_label for custom columns."""
    norm = normalize_lang(lang)
    fallback = str(default_label or col_key or "").strip()
    if norm == "en":
        return fallback
    k = str(col_key or "").strip()
    if not k:
        return fallback
    key = f"col.{k}"
    translated = t(key, norm)
    if translated != key:
        return translated
    return fallback
